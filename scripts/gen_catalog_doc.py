"""Generate docs/SERVICE_CATALOG.md from the YAML catalog (CI fails if it is stale).

python scripts/gen_catalog_doc.py          # write
python scripts/gen_catalog_doc.py --check  # exit 1 if docs/SERVICE_CATALOG.md is out of date
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from exitrisk.catalog import load_catalog  # noqa: E402

OUT = ROOT / "docs" / "SERVICE_CATALOG.md"
TIER_TEXT = {
    1: "Commodity infrastructure or an open standard. Lift-and-shift; configuration moves, code does not change.",
    2: (
        "Managed flavour of an open engine or de-facto standard API. "
        "Data and configuration migrate; little code change."
    ),
    3: "AWS-specific API with a close equivalent on every major cloud. Code changes at the integration points.",
    4: "Proprietary programming or data model. The workload must be redesigned, not just re-pointed.",
    5: "No equivalent outside AWS. Rebuild, re-platform or replace with a product; often a business change.",
}


def cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render() -> str:
    cat = load_catalog()
    lines = [
        "# Service exit-risk catalog",
        "",
        f"<!-- Generated by scripts/gen_catalog_doc.py from src/exitrisk/data/service_catalog.yaml "
        f"(version {cat.version}). Do not edit by hand. -->",
        "",
        "Every AWS service that appears in Cost Explorer is classified into one of five tiers by how much of a "
        "workload must change to leave AWS. The tier sets the service's score in the exit-risk calculation; "
        "the migration path, equivalents and typical duration are for **one workload** of that service. "
        "This is the same content as Appendix A of the generated report.",
        "",
        "| Tier | Label | Score | Meaning |",
        "|---|---|---|---|",
    ]
    for t in range(1, 6):
        lines.append(f"| {t} | {cat.tier_label(t)} | {cat.tier_score(t):g} | {TIER_TEXT[t]} |")
    services = [s for s in cat.services if not s.excluded]
    lines += [
        "",
        f"{len(services)} services classified. Unknown services score as tier 3 and are flagged on the "
        "report's data-quality panel.",
        "",
        "**AI agent help** is how much AI coding agents cut a service's engineering weeks when the Exit model "
        "says teams use them: high about 50% (code and templates an agent can translate), medium about 25%, "
        "low about 10%, none for data moves, hardware, contracts and managed-service redesign.",
        "",
        "**Migration tools** are named where tools do part of the move, with their help on the same scale when "
        "the Exit model says they will be used (never below 30% of the work together with AI agents).",
        "",
    ]
    for t in (5, 4, 3, 2, 1):
        group = sorted((s for s in services if s.tier == t), key=lambda s: (s.category, s.display))
        lines += [
            f"## Tier {t} - {cat.tier_label(t)} ({len(group)})",
            "",
            "| Service | Category | Why this tier | Recommended migration path | Azure | Google Cloud | "
            "Cloud-neutral | Typical duration | Eng-weeks / workload | AI agent help | Migration tools |",
            "|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for s in group:
            tg = s.targets
            lines.append(
                f"| **{cell(s.display)}** | {cell(s.category)} | {cell(s.why)} | {cell(s.migration)} | "
                f"{cell(tg.get('azure', ''))} | {cell(tg.get('gcp', ''))} | {cell(tg.get('other', ''))} | "
                f"{cell(s.duration)} | {s.effort_weeks:g} | {s.agentic} | {tools(s)} |"
            )
        lines.append("")
    excluded = [s for s in cat.services if s.excluded]
    lines += [
        "## Billing lines excluded from scoring",
        "",
        "These are not workloads: " + ", ".join(f"{s.display} ({cell(s.why)})" for s in excluded),
        "",
    ]
    return "\n".join(lines)


def tools(s) -> str:
    if not s.tools:
        return ""
    names = {"all": "", "azure": "Azure: ", "gcp": "Google Cloud: ", "other": "Other: "}
    return cell(f"({s.tooling}) " + "; ".join(names.get(k, k + ": ") + v for k, v in s.tools.items()))


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python scripts/gen_catalog_doc.py", file=sys.stderr)
            return 1
        print("catalog doc up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
